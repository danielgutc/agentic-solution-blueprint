from __future__ import annotations

import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib
import unittest

from tools.docs import check_navigation
from tools.docs import doxygen_markdown as renderer
import xml.etree.ElementTree as ET


HERE = Path(__file__).resolve().parent
TOOL = HERE / "generate_doxygen_docs.py"
FIXTURE = HERE / "fixtures" / "doxygen-generic"
PUBLICATION_FIXTURE = HERE / "fixtures" / "doxygen-publication-v2"
GENERATED_MARKER = "<!-- Generated by tools/docs/generate_doxygen_docs.py; do not edit. -->"


class GenerateDoxygenDocsTests(unittest.TestCase):
    def setUp(self) -> None:
        temp_root = HERE.parent.parent / "artifacts" / "docs-tool-tests"
        temp_root.mkdir(parents=True, exist_ok=True)
        self._temp = tempfile.TemporaryDirectory(dir=temp_root)
        self.root = Path(self._temp.name) / "fixture"
        shutil.copytree(FIXTURE, self.root)
        self.config = self.root / "config.json"

    def tearDown(self) -> None:
        self._temp.cleanup()

    def run_tool(self, *extra: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(TOOL), "--config", str(self.config), *extra],
            cwd=HERE.parent.parent,
            text=True,
            capture_output=True,
            check=False,
        )

    def component_dir(self) -> Path:
        return (
            self.root
            / "repository"
            / "design"
            / "c4"
            / "containers"
            / "sample"
            / "components"
            / "example"
        )

    def test_renders_rich_component_and_api_markdown(self) -> None:
        result = self.run_tool()
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)
        self.assertIn("schema_version 1 is deprecated", result.stderr)

        component = self.component_dir()
        guide = (component / "code.md").read_text(encoding="utf-8")
        api = next((component / "api" / "example-api").glob("*.md")).read_text(encoding="utf-8")
        diagram = (component / "_code-diagrams" / "types.mmd").read_text(encoding="utf-8")

        self.assertIn("[Component architecture]", guide)
        self.assertIn("Doxygen 1.18.0", guide)
        self.assertIn("Example.Api.ClockService", guide)
        self.assertIn("The service keeps formatting separate", api)
        self.assertIn("`format`", api)
        self.assertIn("```csharp", api)
        self.assertIn("The formatted instant.", api)
        self.assertIn("ArgumentException", api)
        self.assertIn("See the clock contract.", api)
        self.assertIn('<a id="member-class-example-api-clockservice-1format"></a>', api)
        self.assertIn("src/Example.Api/ClockService.cs", api)
        self.assertIn("implements", diagram)
        self.assertIn("signature", diagram)

        check = self.run_tool("--check")
        self.assertEqual(0, check.returncode, check.stdout + check.stderr)
        for page in component.rglob("*.md"):
            self.assertEqual([], check_navigation.check(page, self.root / "repository"), str(page))

    def test_refuses_to_overwrite_a_project_owned_guide(self) -> None:
        guide = self.component_dir() / "code.md"
        guide.write_text("Human-owned guide.\n", encoding="utf-8")
        result = self.run_tool()
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(guide.read_text(encoding="utf-8"), "Human-owned guide.\n")

    def test_real_doxygen_nested_blocks_and_code_spaces_are_preserved(self) -> None:
        node = ET.fromstring('''<detaileddescription><para>Use this:
          <programlisting><codeline><highlight>return<sp/>value;</highlight></codeline></programlisting>
          <parameterlist kind="exception"><parameteritem>
            <parameternamelist><parametername>ArgumentException</parametername></parameternamelist>
            <parameterdescription><para>Invalid input.</para></parameterdescription>
          </parameteritem></parameterlist>
        </para></detaileddescription>''')
        result = renderer._description(node, renderer.LinkResolver([]), self.root / "page.md", "csharp")
        self.assertIn("return value;", result)
        self.assertIn("**Exceptions**", result)
        self.assertIn("Invalid input.", result)

    def test_check_reports_stale_and_orphan_generated_files(self) -> None:
        self.assertEqual(0, self.run_tool().returncode)
        component = self.component_dir()
        guide = component / "code.md"
        guide.write_text(guide.read_text(encoding="utf-8") + "stale\n", encoding="utf-8")

        stale = self.run_tool("--check")
        self.assertNotEqual(0, stale.returncode)
        self.assertIn("stale", (stale.stdout + stale.stderr).lower())

        self.assertEqual(0, self.run_tool().returncode)
        orphan = component / "api" / "example-api" / "obsolete.md"
        orphan.write_text(GENERATED_MARKER + "\n", encoding="utf-8")
        orphaned = self.run_tool("--check")
        self.assertNotEqual(0, orphaned.returncode)
        self.assertIn("orphan", (orphaned.stdout + orphaned.stderr).lower())

        self.assertEqual(0, self.run_tool().returncode)
        self.assertFalse(orphan.exists())

    def test_missing_expected_symbol_fails_closed(self) -> None:
        data = json.loads(self.config.read_text(encoding="utf-8"))
        data["components"][0]["expected_symbols"].append("Example.Api.MissingRecord")
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

        result = self.run_tool()
        self.assertNotEqual(0, result.returncode)
        self.assertIn("Example.Api.MissingRecord", result.stdout + result.stderr)

    def test_ambiguous_component_mapping_and_missing_version_fail_closed(self) -> None:
        data = json.loads(self.config.read_text(encoding="utf-8"))
        duplicate = dict(data["components"][0])
        duplicate["id"] = "duplicate"
        duplicate["output_dir"] = "design/c4/containers/sample/components/duplicate"
        duplicate["architecture_page"] = "design/c4/containers/sample/components/example/component.md"
        data["components"].append(duplicate)
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

        ambiguous = self.run_tool()
        self.assertNotEqual(0, ambiguous.returncode)
        self.assertIn("ambiguous", (ambiguous.stdout + ambiguous.stderr).lower())

        data["components"] = data["components"][:1]
        data["doxygen_version"] = ""
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        version = self.run_tool()
        self.assertNotEqual(0, version.returncode)
        self.assertIn("doxygen_version", version.stdout + version.stderr)


class PublicationModelV2Tests(unittest.TestCase):
    def setUp(self) -> None:
        temp_root = HERE.parent.parent / "artifacts" / "docs-tool-tests"
        temp_root.mkdir(parents=True, exist_ok=True)
        self._temp = tempfile.TemporaryDirectory(dir=temp_root)
        self.root = Path(self._temp.name)
        shutil.copytree(FIXTURE, self.root / "doxygen-generic")
        shutil.copytree(PUBLICATION_FIXTURE, self.root / "doxygen-publication-v2")
        self.config = self.root / "doxygen-publication-v2" / "config.json"
        self.repository = self.root / "doxygen-generic" / "repository"

    def tearDown(self) -> None:
        self._temp.cleanup()

    def run_tool(self, *extra: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(TOOL), "--config", str(self.config), *extra],
            cwd=HERE.parent.parent,
            text=True,
            capture_output=True,
            check=False,
        )

    def data(self) -> dict[str, object]:
        return json.loads(self.config.read_text(encoding="utf-8"))

    def write_data(self, data: dict[str, object]) -> None:
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

    def test_publishes_profile_canonical_api_and_link_only_architecture_views(self) -> None:
        result = self.run_tool()
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)

        default_root = self.repository / "design" / "code" / "shared-library" / "default"
        alternate_root = self.repository / "design" / "code" / "shared-library" / "alternate"
        contract = default_root / "api" / "example-api" / "example-api-iclock.md"
        container = self.repository / "design" / "c4" / "containers" / "sample" / "code.md"
        interfaces = container.parent / "_code-views" / "interfaces.md"
        component = container.parent / "components" / "example" / "code.md"
        report_container = self.repository / "design" / "c4" / "containers" / "reporting" / "code.md"
        legacy = component.parent / "api" / "example-api" / "example-api-iclock.md"

        for page in (default_root / "index.md", alternate_root / "index.md", contract,
                     container, interfaces, component, report_container, legacy):
            self.assertTrue(page.is_file(), str(page))

        api = contract.read_text(encoding="utf-8")
        self.assertIn("Example.Api.IClock", api)
        self.assertIn("IClock.Now", api)
        self.assertIn("All bound views", api)
        self.assertIn("Sample container", api)
        self.assertIn("Report reader", api)
        self.assertIn("exported-api.txt", api)

        for view in (container, interfaces, component, report_container):
            content = view.read_text(encoding="utf-8")
            self.assertIn("example-api-iclock.md", content)
            self.assertNotIn("IClock.Now", content)

        interface_content = interfaces.read_text(encoding="utf-8")
        self.assertIn("Provided external runtime ports", interface_content)
        self.assertIn("Provided internal component ports", interface_content)
        self.assertIn("Consumed internal component ports", interface_content)
        self.assertIn("The component implements the container", component.read_text(encoding="utf-8"))
        self.assertIn("moved", legacy.read_text(encoding="utf-8").lower())
        self.assertNotIn("## Members", legacy.read_text(encoding="utf-8"))

        self.assertEqual(0, self.run_tool("--check").returncode)
        for page in self.repository.rglob("*.md"):
            if page.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
                self.assertEqual([], check_navigation.check(page, self.repository), str(page))

    def test_container_without_component_decomposition_is_supported(self) -> None:
        data = self.data()
        data["architecture"]["components"] = []
        data["profiles"] = data["profiles"][:1]
        for binding in data["profiles"][0]["bindings"]:
            binding.pop("component_id", None)
        self.write_data(data)

        result = self.run_tool()
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)
        container = self.repository / "design" / "c4" / "containers" / "sample" / "code.md"
        self.assertTrue(container.is_file())
        self.assertIn("No approved component decomposition is configured", container.read_text(encoding="utf-8"))
        self.assertFalse((container.parent / "components" / "example" / "code.md").exists())

    def test_rejects_missing_selectors_duplicate_keys_and_stale_architecture_ids(self) -> None:
        data = self.data()
        data["profiles"][0]["symbols"][0]["selectors"] = {}
        self.write_data(data)
        missing = self.run_tool()
        self.assertNotEqual(0, missing.returncode)
        self.assertIn("selector", (missing.stdout + missing.stderr).lower())

        data = json.loads((PUBLICATION_FIXTURE / "config.json").read_text(encoding="utf-8"))
        data["profiles"][0]["symbols"].append(dict(data["profiles"][0]["symbols"][0]))
        self.write_data(data)
        duplicate = self.run_tool()
        self.assertNotEqual(0, duplicate.returncode)
        self.assertIn("duplicate symbol key", (duplicate.stdout + duplicate.stderr).lower())

        data = json.loads((PUBLICATION_FIXTURE / "config.json").read_text(encoding="utf-8"))
        data["profiles"][0]["bindings"][0]["component_id"] = "removed-component"
        self.write_data(data)
        stale = self.run_tool()
        self.assertNotEqual(0, stale.returncode)
        self.assertIn("unknown component", (stale.stdout + stale.stderr).lower())

        data = json.loads((PUBLICATION_FIXTURE / "config.json").read_text(encoding="utf-8"))
        data["profiles"][0]["bindings"][0].pop("interface_scope")
        self.write_data(data)
        missing_scope = self.run_tool()
        self.assertNotEqual(0, missing_scope.returncode)
        self.assertIn("interface_scope", missing_scope.stdout + missing_scope.stderr)

    def test_rejects_conflicting_owners_and_case_colliding_profiles(self) -> None:
        data = self.data()
        conflict = dict(next(
            item for item in data["profiles"][0]["bindings"]
            if item["role"] == "owned-implementation"
        ))
        conflict["container_id"] = "reporting"
        conflict["component_id"] = "report-reader"
        data["profiles"][0]["bindings"].append(conflict)
        self.write_data(data)
        owners = self.run_tool()
        self.assertNotEqual(0, owners.returncode)
        self.assertIn("conflicting owner", (owners.stdout + owners.stderr).lower())

        data = json.loads((PUBLICATION_FIXTURE / "config.json").read_text(encoding="utf-8"))
        data["profiles"][1]["id"] = "DEFAULT"
        self.write_data(data)
        collision = self.run_tool()
        self.assertNotEqual(0, collision.returncode)
        self.assertIn("duplicate profile id", (collision.stdout + collision.stderr).lower())

    def test_rejects_missing_native_inventory_evidence_and_inventory_drift(self) -> None:
        data = self.data()
        data["profiles"][0]["inventory_evidence"] = "docs/missing-native-inventory.txt"
        self.write_data(data)
        evidence = self.run_tool()
        self.assertNotEqual(0, evidence.returncode)
        self.assertIn("inventory_evidence does not exist", (evidence.stdout + evidence.stderr).lower())

        data = json.loads((PUBLICATION_FIXTURE / "config.json").read_text(encoding="utf-8"))
        data["profiles"][0]["symbols"] = data["profiles"][0]["symbols"][:1]
        data["profiles"][0]["bindings"] = [
            item for item in data["profiles"][0]["bindings"]
            if item["symbol_key"] == "example-api-iclock"
        ]
        self.write_data(data)
        drift = self.run_tool()
        self.assertNotEqual(0, drift.returncode)
        self.assertIn("unconfigured exported symbols", (drift.stdout + drift.stderr).lower())

    def test_portable_manifest_carries_schema_v2_helper_and_fixtures(self) -> None:
        manifest = tomllib.loads(
            (HERE.parent.parent / ".blueprint" / "tooling.toml").read_text(encoding="utf-8")
        )
        files = set(manifest["files"])
        required = {
            "tools/docs/doxygen_publication.py",
            "tools/docs/fixtures/doxygen-publication-v2/config.json",
            "tools/docs/fixtures/doxygen-generic/repository/design/c4/containers/sample/container.md",
            "tools/docs/fixtures/doxygen-generic/repository/design/c4/containers/reporting/container.md",
            "tools/docs/fixtures/doxygen-generic/repository/docs/exported-api.txt",
        }
        self.assertEqual(set(), required - files)

    def test_orphan_cleanup_removes_only_owned_marker_files(self) -> None:
        self.assertEqual(0, self.run_tool().returncode)
        canonical = self.repository / "design" / "code" / "shared-library" / "default" / "api"
        orphan = canonical / "obsolete.md"
        human = canonical / "notes.md"
        orphan.write_text(GENERATED_MARKER + "\n\n# Obsolete\n", encoding="utf-8")
        human.write_text("# Human notes\n", encoding="utf-8")
        legacy_root = (
            self.repository / "design" / "c4" / "containers" / "sample" / "components"
            / "example" / "api"
        )
        legacy_orphan = legacy_root / "obsolete.md"
        legacy_orphan.write_text(GENERATED_MARKER + "\n\n# Obsolete\n", encoding="utf-8")

        checked = self.run_tool("--check")
        self.assertNotEqual(0, checked.returncode)
        self.assertIn("orphan", (checked.stdout + checked.stderr).lower())
        self.assertEqual(0, self.run_tool().returncode)
        self.assertFalse(orphan.exists())
        self.assertFalse(legacy_orphan.exists())
        self.assertTrue(human.is_file())


