from __future__ import annotations

import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

from tools.docs import check_navigation
from tools.docs import doxygen_markdown as renderer
import xml.etree.ElementTree as ET


HERE = Path(__file__).resolve().parent
TOOL = HERE / "generate_doxygen_docs.py"
FIXTURE = HERE / "fixtures" / "doxygen-generic"
GENERATED_MARKER = "<!-- Generated by tools/docs/generate_doxygen_docs.py; do not edit. -->"


class GenerateDoxygenDocsTests(unittest.TestCase):
    def setUp(self) -> None:
        temp_root = HERE.parent.parent / "artifacts" / "docs-tool-tests"
        temp_root.mkdir(parents=True, exist_ok=True)
        self._temp = tempfile.TemporaryDirectory(dir=temp_root)
        self.root = Path(self._temp.name) / "fixture"
        shutil.copytree(FIXTURE, self.root)
        self.config = self.root / "config.json"

    def tearDown(self) -> None:
        self._temp.cleanup()

    def run_tool(self, *extra: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(TOOL), "--config", str(self.config), *extra],
            cwd=HERE.parent.parent,
            text=True,
            capture_output=True,
            check=False,
        )

    def component_dir(self) -> Path:
        return (
            self.root
            / "repository"
            / "design"
            / "c4"
            / "containers"
            / "sample"
            / "components"
            / "example"
        )

    def test_renders_rich_component_and_api_markdown(self) -> None:
        result = self.run_tool()
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)

        component = self.component_dir()
        guide = (component / "code.md").read_text(encoding="utf-8")
        api = next((component / "api" / "example-api").glob("*.md")).read_text(encoding="utf-8")
        diagram = (component / "_code-diagrams" / "types.mmd").read_text(encoding="utf-8")

        self.assertIn("[Component architecture]", guide)
        self.assertIn("Doxygen 1.18.0", guide)
        self.assertIn("Example.Api.ClockService", guide)
        self.assertIn("The service keeps formatting separate", api)
        self.assertIn("`format`", api)
        self.assertIn("```csharp", api)
        self.assertIn("The formatted instant.", api)
        self.assertIn("ArgumentException", api)
        self.assertIn("See the clock contract.", api)
        self.assertIn('<a id="member-class-example-api-clockservice-1format"></a>', api)
        self.assertIn("src/Example.Api/ClockService.cs", api)
        self.assertIn("implements", diagram)
        self.assertIn("signature", diagram)

        check = self.run_tool("--check")
        self.assertEqual(0, check.returncode, check.stdout + check.stderr)
        for page in component.rglob("*.md"):
            self.assertEqual([], check_navigation.check(page, self.root / "repository"), str(page))

    def test_refuses_to_overwrite_a_project_owned_guide(self) -> None:
        guide = self.component_dir() / "code.md"
        guide.write_text("Human-owned guide.\n", encoding="utf-8")
        result = self.run_tool()
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(guide.read_text(encoding="utf-8"), "Human-owned guide.\n")

    def test_real_doxygen_nested_blocks_and_code_spaces_are_preserved(self) -> None:
        node = ET.fromstring('''<detaileddescription><para>Use this:
          <programlisting><codeline><highlight>return<sp/>value;</highlight></codeline></programlisting>
          <parameterlist kind="exception"><parameteritem>
            <parameternamelist><parametername>ArgumentException</parametername></parameternamelist>
            <parameterdescription><para>Invalid input.</para></parameterdescription>
          </parameteritem></parameterlist>
        </para></detaileddescription>''')
        result = renderer._description(node, renderer.LinkResolver([]), self.root / "page.md", "csharp")
        self.assertIn("return value;", result)
        self.assertIn("**Exceptions**", result)
        self.assertIn("Invalid input.", result)

    def test_check_reports_stale_and_orphan_generated_files(self) -> None:
        self.assertEqual(0, self.run_tool().returncode)
        component = self.component_dir()
        guide = component / "code.md"
        guide.write_text(guide.read_text(encoding="utf-8") + "stale\n", encoding="utf-8")

        stale = self.run_tool("--check")
        self.assertNotEqual(0, stale.returncode)
        self.assertIn("stale", (stale.stdout + stale.stderr).lower())

        self.assertEqual(0, self.run_tool().returncode)
        orphan = component / "api" / "example-api" / "obsolete.md"
        orphan.write_text(GENERATED_MARKER + "\n", encoding="utf-8")
        orphaned = self.run_tool("--check")
        self.assertNotEqual(0, orphaned.returncode)
        self.assertIn("orphan", (orphaned.stdout + orphaned.stderr).lower())

        self.assertEqual(0, self.run_tool().returncode)
        self.assertFalse(orphan.exists())

    def test_missing_expected_symbol_fails_closed(self) -> None:
        data = json.loads(self.config.read_text(encoding="utf-8"))
        data["components"][0]["expected_symbols"].append("Example.Api.MissingRecord")
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

        result = self.run_tool()
        self.assertNotEqual(0, result.returncode)
        self.assertIn("Example.Api.MissingRecord", result.stdout + result.stderr)

    def test_ambiguous_component_mapping_and_missing_version_fail_closed(self) -> None:
        data = json.loads(self.config.read_text(encoding="utf-8"))
        duplicate = dict(data["components"][0])
        duplicate["id"] = "duplicate"
        duplicate["output_dir"] = "design/c4/containers/sample/components/duplicate"
        duplicate["architecture_page"] = "design/c4/containers/sample/components/example/component.md"
        data["components"].append(duplicate)
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

        ambiguous = self.run_tool()
        self.assertNotEqual(0, ambiguous.returncode)
        self.assertIn("ambiguous", (ambiguous.stdout + ambiguous.stderr).lower())

        data["components"] = data["components"][:1]
        data["doxygen_version"] = ""
        self.config.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        version = self.run_tool()
        self.assertNotEqual(0, version.returncode)
        self.assertIn("doxygen_version", version.stdout + version.stderr)


if __name__ == "__main__":
    unittest.main()
