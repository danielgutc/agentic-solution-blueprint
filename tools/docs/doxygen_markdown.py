"""Reusable Doxygen XML to component-owned Markdown projection helpers."""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET


GENERATED_MARKER = "<!-- Generated by tools/docs/generate_doxygen_docs.py; do not edit. -->"
MERMAID_MARKER = "%% Generated by tools/docs/generate_doxygen_docs.py; do not edit."
SUPPORTED_COMPOUND_KINDS = {"class", "struct", "interface"}
SUPPORTED_DESCRIPTION_TAGS = {
    "para",
    "programlisting",
    "parameterlist",
    "simplesect",
    "itemizedlist",
    "orderedlist",
    "heading",
}


class DocumentationError(RuntimeError):
    """Raised when source documentation cannot be projected without guessing."""


@dataclass(frozen=True)
class ComponentConfig:
    id: str
    title: str
    output_dir: Path
    architecture_page: Path
    api_scope: str
    qualified_prefixes: tuple[str, ...]
    source_prefixes: tuple[str, ...]
    compound_ids: tuple[str, ...]
    expected_symbols: tuple[str, ...]


@dataclass(frozen=True)
class Config:
    path: Path
    schema_version: int
    doxygen_version: str
    doxyfile: Path
    doxygen_xml: Path
    repository_root: Path
    reproduce_command: str
    code_fence_language: str
    components: tuple[ComponentConfig, ...]


@dataclass(frozen=True)
class Location:
    file: str
    line: int | None


@dataclass
class Member:
    id: str
    kind: str
    protection: str
    name: str
    definition: str
    args: str
    brief: ET.Element | None
    detail: ET.Element | None
    location: Location
    referenced_ids: set[str]


@dataclass
class Compound:
    id: str
    kind: str
    protection: str
    qualified_name: str
    language: str
    brief: ET.Element | None
    detail: ET.Element | None
    location: Location
    base_ids: tuple[str, ...]
    members: list[Member]
    component: ComponentConfig | None = None


def _within(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def _required_string(data: dict[str, object], key: str) -> str:
    value = data.get(key)
    if not isinstance(value, str) or not value.strip():
        raise DocumentationError(f"{key} must be a non-empty string")
    return value.strip()


def _string_list(data: dict[str, object], key: str) -> tuple[str, ...]:
    value = data.get(key, [])
    if not isinstance(value, list) or not all(isinstance(item, str) and item for item in value):
        raise DocumentationError(f"{key} must be a list of non-empty strings")
    return tuple(value)


def load_config(path: Path) -> Config:
    path = path.resolve()
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DocumentationError(f"cannot read config {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise DocumentationError("configuration root must be an object")
    if data.get("schema_version") != 1:
        raise DocumentationError("schema_version must be 1")

    base = path.parent
    repository_root = (base / _required_string(data, "repository_root")).resolve()
    doxygen_xml = (base / _required_string(data, "doxygen_xml")).resolve()
    doxyfile = (base / _required_string(data, "doxyfile")).resolve()
    if not repository_root.is_dir():
        raise DocumentationError(f"repository_root does not exist: {repository_root}")
    if not doxyfile.is_file():
        raise DocumentationError(f"doxyfile does not exist: {doxyfile}")

    raw_components = data.get("components")
    if not isinstance(raw_components, list) or not raw_components:
        raise DocumentationError("components must be a non-empty list")
    components: list[ComponentConfig] = []
    seen_ids: set[str] = set()
    seen_outputs: set[Path] = set()
    for index, raw in enumerate(raw_components):
        if not isinstance(raw, dict):
            raise DocumentationError(f"components[{index}] must be an object")
        component_id = _required_string(raw, "id")
        if component_id in seen_ids:
            raise DocumentationError(f"duplicate component id: {component_id}")
        seen_ids.add(component_id)
        output_dir = (repository_root / _required_string(raw, "output_dir")).resolve()
        architecture_page = (repository_root / _required_string(raw, "architecture_page")).resolve()
        if not _within(output_dir, repository_root):
            raise DocumentationError(f"component output escapes repository_root: {output_dir}")
        if output_dir in seen_outputs:
            raise DocumentationError(f"duplicate component output_dir: {output_dir}")
        seen_outputs.add(output_dir)
        if not architecture_page.is_file():
            raise DocumentationError(f"architecture_page does not exist: {architecture_page}")
        if not _within(architecture_page, repository_root):
            raise DocumentationError("architecture_page escapes repository_root")
        api_scope = _required_string(raw, "api_scope")
        api_scope_path = Path(api_scope)
        if api_scope_path.is_absolute() or ".." in api_scope_path.parts:
            raise DocumentationError(f"api_scope must be a safe relative path: {api_scope}")
        prefixes = _string_list(raw, "qualified_prefixes")
        source_prefixes = tuple(item.replace("\\", "/") for item in _string_list(raw, "source_prefixes"))
        compound_ids = _string_list(raw, "compound_ids")
        if not prefixes and not source_prefixes and not compound_ids:
            raise DocumentationError(f"component {component_id} has no ownership selector")
        expected_symbols = _string_list(raw, "expected_symbols")
        if not expected_symbols:
            raise DocumentationError(f"component {component_id} must declare expected_symbols")
        components.append(
            ComponentConfig(
                id=component_id,
                title=_required_string(raw, "title"),
                output_dir=output_dir,
                architecture_page=architecture_page,
                api_scope=api_scope_path.as_posix(),
                qualified_prefixes=prefixes,
                source_prefixes=source_prefixes,
                compound_ids=compound_ids,
                expected_symbols=expected_symbols,
            )
        )

    return Config(
        path=path,
        schema_version=1,
        doxygen_version=_required_string(data, "doxygen_version"),
        doxyfile=doxyfile,
        doxygen_xml=doxygen_xml,
        repository_root=repository_root,
        reproduce_command=_required_string(data, "reproduce_command"),
        code_fence_language=str(data.get("code_fence_language", "")).strip(),
        components=tuple(components),
    )


def doxygen_version(executable: str) -> str:
    try:
        result = subprocess.run(
            [executable, "--version"], text=True, capture_output=True, check=False
        )
    except OSError as exc:
        raise DocumentationError(f"cannot execute Doxygen at {executable}: {exc}") from exc
    if result.returncode != 0:
        raise DocumentationError(f"Doxygen version check failed: {result.stderr.strip()}")
    version = result.stdout.strip().splitlines()[0] if result.stdout.strip() else ""
    if not version:
        raise DocumentationError("Doxygen returned an empty version")
    return version


def run_doxygen(config: Config, executable: str) -> None:
    actual = doxygen_version(executable)
    if actual != config.doxygen_version:
        raise DocumentationError(
            f"Doxygen version mismatch: configured {config.doxygen_version}, found {actual}"
        )
    result = subprocess.run(
        [executable, str(config.doxyfile)],
        cwd=config.doxyfile.parent,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise DocumentationError(f"Doxygen generation failed: {detail}")
    if result.stderr.strip():
        raise DocumentationError(f"Doxygen reported diagnostics: {result.stderr.strip()}")


def _location(element: ET.Element, qualified_name: str) -> Location:
    node = element.find("location")
    if node is None or not node.get("file"):
        raise DocumentationError(f"{qualified_name} has no source location")
    line_text = node.get("line")
    return Location(node.get("file", "").replace("\\", "/"), int(line_text) if line_text else None)


def _element_text(element: ET.Element | None) -> str:
    if element is None:
        return ""
    return " ".join("".join(element.itertext()).split())


def load_compounds(config: Config) -> list[Compound]:
    try:
        index = ET.parse(config.doxygen_xml / "index.xml").getroot()
    except (OSError, ET.ParseError) as exc:
        raise DocumentationError(f"cannot parse Doxygen index: {exc}") from exc
    if index.get("version") != config.doxygen_version.split()[0]:
        raise DocumentationError("Doxygen XML version does not match the configured version")
    compounds: list[Compound] = []
    for entry in index.findall("compound"):
        kind = entry.get("kind", "")
        if kind not in SUPPORTED_COMPOUND_KINDS:
            continue
        refid = entry.get("refid", "")
        if not refid:
            raise DocumentationError("Doxygen compound has no refid")
        compound_file = config.doxygen_xml / f"{refid}.xml"
        try:
            root = ET.parse(compound_file).getroot()
        except (OSError, ET.ParseError) as exc:
            raise DocumentationError(f"cannot parse {compound_file}: {exc}") from exc
        node = root.find("compounddef")
        if node is None:
            raise DocumentationError(f"{compound_file} has no compounddef")
        protection = node.get("prot", "public")
        if protection not in {"public", "protected"}:
            continue
        name = _element_text(node.find("compoundname"))
        if node.get("language") == "C#":
            name = name.replace("::", ".")
        if not name:
            raise DocumentationError(f"{refid} has no compoundname")
        members: list[Member] = []
        for member_node in node.findall("./sectiondef/memberdef"):
            member_protection = member_node.get("prot", "public")
            if member_protection not in {"public", "protected"}:
                continue
            member_id = member_node.get("id", "")
            member_name = _element_text(member_node.find("name"))
            if not member_id or not member_name:
                raise DocumentationError(f"{name} has a public member without a stable id or name")
            referenced = {
                item.get("refid", "")
                for item in member_node.findall(".//type//ref")
                + member_node.findall(".//argsstring//ref")
                + member_node.findall(".//param//ref")
                if item.get("refid")
            }
            members.append(
                Member(
                    id=member_id,
                    kind=member_node.get("kind", "member"),
                    protection=member_protection,
                    name=member_name,
                    definition=_element_text(member_node.find("definition")),
                    args=_element_text(member_node.find("argsstring")),
                    brief=member_node.find("briefdescription"),
                    detail=member_node.find("detaileddescription"),
                    location=_location(member_node, f"{name}.{member_name}"),
                    referenced_ids=referenced,
                )
            )
        compounds.append(
            Compound(
                id=refid,
                kind=kind,
                protection=protection,
                qualified_name=name,
                language=node.get("language", ""),
                brief=node.find("briefdescription"),
                detail=node.find("detaileddescription"),
                location=_location(node, name),
                base_ids=tuple(
                    base.get("refid", "")
                    for base in node.findall("basecompoundref")
                    if base.get("refid")
                ),
                members=members,
            )
        )
    return compounds


def assign_components(config: Config, compounds: list[Compound]) -> None:
    for compound in compounds:
        source = _source_path(config, compound.location).relative_to(config.repository_root).as_posix()
        matches: list[ComponentConfig] = []
        for component in config.components:
            if (
                compound.id in component.compound_ids
                or any(compound.qualified_name.startswith(prefix) for prefix in component.qualified_prefixes)
                or any(source.startswith(prefix) for prefix in component.source_prefixes)
            ):
                matches.append(component)
        if not matches:
            raise DocumentationError(f"unmapped public compound: {compound.qualified_name}")
        if len(matches) > 1:
            ids = ", ".join(item.id for item in matches)
            raise DocumentationError(f"ambiguous component mapping for {compound.qualified_name}: {ids}")
        compound.component = matches[0]

    for component in config.components:
        actual = {
            compound.qualified_name
            for compound in compounds
            if compound.component is not None and compound.component.id == component.id
        }
        expected = set(component.expected_symbols)
        missing = sorted(expected - actual)
        unexpected = sorted(actual - expected)
        if missing or unexpected:
            parts: list[str] = []
            if missing:
                parts.append("missing: " + ", ".join(missing))
            if unexpected:
                parts.append("not in expected_symbols: " + ", ".join(unexpected))
            raise DocumentationError(f"component {component.id} coverage mismatch ({'; '.join(parts)})")


def _slug(value: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "-", value).strip("-").lower()
    if not slug:
        raise DocumentationError(f"cannot create stable identifier from {value!r}")
    return slug


def _api_path(compound: Compound) -> Path:
    assert compound.component is not None
    return compound.component.output_dir / "api" / compound.component.api_scope / f"{_slug(compound.id)}.md"


def _relative_link(source: Path, target: Path, fragment: str = "") -> str:
    if source.resolve() == target.resolve() and fragment:
        return f"#{fragment}"
    relative = os.path.relpath(target, source.parent).replace("\\", "/")
    return relative + (f"#{fragment}" if fragment else "")


class LinkResolver:
    def __init__(self, compounds: list[Compound]) -> None:
        self.compounds = {compound.id: compound for compound in compounds}
        self.members: dict[str, tuple[Compound, Member]] = {}
        for compound in compounds:
            for member in compound.members:
                self.members[member.id] = (compound, member)

    def link(self, refid: str, source_page: Path) -> str | None:
        compound = self.compounds.get(refid)
        if compound is not None:
            return _relative_link(source_page, _api_path(compound))
        member = self.members.get(refid)
        if member is not None:
            owner, value = member
            return _relative_link(source_page, _api_path(owner), f"member-{_slug(value.id)}")
        return None


def _inline(element: ET.Element, resolver: LinkResolver, source_page: Path, language: str = "") -> str:
    pieces: list[str] = []
    if element.text:
        pieces.append(re.sub(r"\s+", " ", element.text))
    for child in element:
        tag = child.tag.rsplit("}", 1)[-1]
        text = " ".join("".join(child.itertext()).split())
        if tag in SUPPORTED_DESCRIPTION_TAGS:
            wrapper = ET.Element("description")
            wrapper.append(child)
            pieces.append("\n\n" + _description(wrapper, resolver, source_page, language) + "\n\n")
        elif tag in {"parametername", "paramref", "computeroutput", "codeline", "highlight"}:
            value = child.get("name") or text
            pieces.append(f"`{value}`")
        elif tag == "ref":
            label = text or child.get("refid", "reference")
            link = resolver.link(child.get("refid", ""), source_page)
            pieces.append(f"[{label}]({link})" if link else f"`{label}`")
        elif tag == "seealso":
            label = text or child.get("cref", "reference")
            pieces.append(f"{label} (`{child.get('cref', '')}`)")
        elif tag in {"bold", "b"}:
            pieces.append(f"**{text}**")
        elif tag in {"emphasis", "em"}:
            pieces.append(f"*{text}*")
        elif tag == "ulink":
            pieces.append(f"[{text}]({child.get('url', '')})")
        elif tag == "linebreak":
            pieces.append("  \n")
        elif tag == "sp":
            pieces.append(" ")
        else:
            raise DocumentationError(f"unsupported inline Doxygen tag <{tag}>")
        if child.tail:
            pieces.append(re.sub(r"\s+", " ", child.tail))
    return "".join(pieces).strip()


def _program_listing(element: ET.Element, language: str) -> str:
    def code_text(node: ET.Element) -> str:
        if node.tag == "sp":
            return " "
        return (node.text or "") + "".join(code_text(child) + (child.tail or "") for child in node)

    lines = [code_text(line) for line in element.findall("codeline")]
    if not lines:
        lines = ["".join(element.itertext())]
    return f"```{language}\n" + "\n".join(lines).rstrip() + "\n```"


def _list_block(element: ET.Element, resolver: LinkResolver, source_page: Path, ordered: bool) -> str:
    lines: list[str] = []
    for index, item in enumerate(element.findall("listitem"), start=1):
        paras = item.findall("para")
        if not paras:
            raise DocumentationError("Doxygen listitem has no para")
        prefix = f"{index}." if ordered else "-"
        lines.append(f"{prefix} {_inline(paras[0], resolver, source_page)}")
    return "\n".join(lines)


def _parameter_table(element: ET.Element, resolver: LinkResolver, source_page: Path) -> str:
    rows = ["| Parameter | Description |", "| --- | --- |"]
    for item in element.findall("parameteritem"):
        names = [
            _inline(name, resolver, source_page)
            for name in item.findall("./parameternamelist/parametername")
        ]
        description = item.find("parameterdescription")
        if not names or description is None:
            raise DocumentationError("incomplete Doxygen parameteritem")
        rendered = _description(description, resolver, source_page, "").replace("\n", " ")
        rows.append(f"| {', '.join(names)} | {rendered} |")
    return "\n".join(rows)


def _simple_section(element: ET.Element, resolver: LinkResolver, source_page: Path) -> str:
    kind = element.get("kind", "")
    labels = {
        "return": "Returns",
        "exception": "Exceptions",
        "see": "See also",
        "note": "Note",
        "warning": "Warning",
        "pre": "Preconditions",
        "post": "Postconditions",
        "invariant": "Invariants",
        "remark": "Remarks",
    }
    label = labels.get(kind)
    if label is None:
        raise DocumentationError(f"unsupported Doxygen simplesect kind {kind!r}")
    body = "\n\n".join(_inline(para, resolver, source_page) for para in element.findall("para"))
    return f"**{label}:** {body}".rstrip()


def _description(
    element: ET.Element | None,
    resolver: LinkResolver,
    source_page: Path,
    language: str,
) -> str:
    if element is None:
        return ""
    blocks: list[str] = []
    for child in element:
        tag = child.tag.rsplit("}", 1)[-1]
        if tag not in SUPPORTED_DESCRIPTION_TAGS:
            raise DocumentationError(f"unsupported Doxygen description tag <{tag}>")
        if tag == "para":
            blocks.append(_inline(child, resolver, source_page, language))
        elif tag == "programlisting":
            blocks.append(_program_listing(child, language))
        elif tag == "parameterlist":
            kind = child.get("kind", "")
            if kind not in {"param", "templateparam", "exception"}:
                raise DocumentationError(f"unsupported parameterlist kind {kind!r}")
            heading = {"param": "Parameters", "templateparam": "Type parameters", "exception": "Exceptions"}[kind]
            blocks.append(f"**{heading}**\n\n{_parameter_table(child, resolver, source_page)}")
        elif tag == "simplesect":
            blocks.append(_simple_section(child, resolver, source_page))
        elif tag == "itemizedlist":
            blocks.append(_list_block(child, resolver, source_page, False))
        elif tag == "orderedlist":
            blocks.append(_list_block(child, resolver, source_page, True))
        elif tag == "heading":
            blocks.append(f"**{_inline(child, resolver, source_page)}**")
    return "\n\n".join(block for block in blocks if block.strip())


def _source_path(config: Config, location: Location) -> Path:
    raw = Path(location.file)
    path = raw.resolve() if raw.is_absolute() else (config.repository_root / raw).resolve()
    if not _within(path, config.repository_root):
        raise DocumentationError(f"source location escapes repository_root: {location.file}")
    if not path.is_file():
        raise DocumentationError(f"source location does not exist: {location.file}")
    return path


def _source_link(config: Config, page: Path, location: Location) -> str:
    path = _source_path(config, location)
    label = path.relative_to(config.repository_root).as_posix()
    fragment = f"L{location.line}" if location.line else ""
    return f"[{label}]({_relative_link(page, path, fragment)})"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_text(encoding="utf-8").encode("utf-8")).hexdigest()


def _provenance(config: Config) -> str:
    return (
        f"Doxygen {config.doxygen_version}; LF-normalized config SHA-256 `{_sha256(config.path)}`; "
        f"Doxyfile SHA-256 `{_sha256(config.doxyfile)}`. Regenerate with "
        f"`{config.reproduce_command}`."
    )


def _with_contents(content: str) -> str:
    headings = []
    fenced = False
    for line in content.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        if not fenced and line.startswith("## "):
            headings.append(line[3:])
    toc = ["## Table of contents", ""]
    toc.extend(f"- [{heading}](#{_slug(heading)})" for heading in headings)
    offset = content.find("\n## ")
    if offset < 0:
        return content
    return content[:offset] + "\n" + "\n".join(toc) + "\n" + content[offset:]


def _render_api(
    config: Config,
    compound: Compound,
    resolver: LinkResolver,
    by_id: dict[str, Compound],
) -> str:
    assert compound.component is not None
    page = _api_path(compound)
    architecture_link = _relative_link(page, compound.component.architecture_page)
    guide_link = _relative_link(page, compound.component.output_dir / "code.md")
    lines = [
        GENERATED_MARKER,
        "",
        f"# `{compound.qualified_name}`",
        "",
        f"[Component architecture]({architecture_link}) | [Code guide]({guide_link})",
        "",
        f"**Kind:** `{compound.kind}`", "",
        f"**Language:** `{compound.language or 'unspecified'}`", "",
        f"**Source:** {_source_link(config, page, compound.location)}",
        "",
        "## Summary",
        "",
        _description(compound.brief, resolver, page, config.code_fence_language) or "No summary was authored.",
    ]
    detail = _description(compound.detail, resolver, page, config.code_fence_language)
    if detail:
        lines.extend(["", "## Remarks", "", detail])
    if compound.base_ids:
        lines.extend(["", "## Relationships", ""])
        for base_id in compound.base_ids:
            base = by_id.get(base_id)
            if base is None:
                raise DocumentationError(f"unresolved base relationship {base_id} for {compound.qualified_name}")
            relation = "implements" if base.kind == "interface" else "inherits"
            link = resolver.link(base_id, page)
            lines.append(f"- {relation} [`{base.qualified_name}`]({link}) (Doxygen base relationship)")
    if compound.members:
        lines.extend(["", "## Members", ""])
    for member in compound.members:
        anchor = f"member-{_slug(member.id)}"
        signature = (member.definition + member.args).strip() or member.name
        lines.extend(
            [
                f'<a id="{anchor}"></a>',
                "",
                f"### `{member.name}`",
                "",
                f"```{config.code_fence_language}\n{signature}\n```",
                "",
                f"**Kind:** `{member.kind}`", "",
                f"**Source:** {_source_link(config, page, member.location)}",
                "",
                _description(member.brief, resolver, page, config.code_fence_language)
                or "No summary was authored.",
            ]
        )
        member_detail = _description(member.detail, resolver, page, config.code_fence_language)
        if member_detail:
            lines.extend(["", member_detail])
    lines.extend(["", "## Provenance", "", _provenance(config), ""])
    return _with_contents("\n".join(lines))


def _render_guide(
    config: Config,
    component: ComponentConfig,
    compounds: list[Compound],
    resolver: LinkResolver,
    relations: list[tuple[Compound, Compound, str]],
) -> str:
    page = component.output_dir / "code.md"
    architecture_link = _relative_link(page, component.architecture_page)
    diagram = component.output_dir / "_code-diagrams" / "types.mmd"
    lines = [
        GENERATED_MARKER,
        "",
        f"# {component.title} code documentation",
        "",
        f"[Component architecture]({architecture_link}) | [Relationship diagram source]({_relative_link(page, diagram)})",
        "",
        "This guide projects source-authored API documentation and structural relationships reported by Doxygen.",
        "",
        "## Public types",
        "",
        "| Type | Kind | Purpose | Source |",
        "| --- | --- | --- | --- |",
    ]
    for compound in sorted(compounds, key=lambda item: item.qualified_name):
        link = _relative_link(page, _api_path(compound))
        summary = _description(compound.brief, resolver, page, config.code_fence_language).replace("\n", " ")
        source = _source_link(config, page, compound.location)
        lines.append(f"| [`{compound.qualified_name}`]({link}) | `{compound.kind}` | {summary} | {source} |")
    lines.extend(["", "## Authored guidance", ""])
    for compound in sorted(compounds, key=lambda item: item.qualified_name):
        detail = _description(compound.detail, resolver, page, config.code_fence_language)
        if detail:
            link = _relative_link(page, _api_path(compound))
            lines.extend([f"### [{compound.qualified_name}]({link})", "", detail, ""])
    lines.extend(["", "## Documented relationships", ""])
    if relations:
        lines.extend(["| Source | Relationship | Target | Evidence |", "| --- | --- | --- | --- |"])
        for source, target, relation in relations:
            source_link = _relative_link(page, _api_path(source))
            target_link = _relative_link(page, _api_path(target))
            evidence = "Doxygen base relationship" if relation in {"implements", "inherits"} else "Doxygen signature reference"
            lines.append(
                f"| [`{source.qualified_name}`]({source_link}) | {relation} | "
                f"[`{target.qualified_name}`]({target_link}) | {evidence} |"
            )
    else:
        lines.append("No relationships were reported for this configured scope.")
    lines.extend(["", "## Relationship diagram", "", "```mermaid",
                  *_render_diagram(compounds, relations).splitlines()[1:], "```"])
    lines.extend(["", "## Provenance", "", _provenance(config), ""])
    return _with_contents("\n".join(lines))


def _relations(compounds: list[Compound]) -> list[tuple[Compound, Compound, str]]:
    by_id = {compound.id: compound for compound in compounds}
    result: set[tuple[str, str, str]] = set()
    for compound in compounds:
        for base_id in compound.base_ids:
            target = by_id.get(base_id)
            if target is None:
                raise DocumentationError(f"unresolved base relationship {base_id} for {compound.qualified_name}")
            result.add((compound.id, target.id, "implements" if target.kind == "interface" else "inherits"))
        for member in compound.members:
            for refid in member.referenced_ids:
                target = by_id.get(refid)
                if target is not None and target.id != compound.id:
                    result.add((compound.id, target.id, "signature"))
    return [
        (by_id[source_id], by_id[target_id], relation)
        for source_id, target_id, relation in sorted(result)
    ]


def _render_diagram(compounds: list[Compound], relations: list[tuple[Compound, Compound, str]]) -> str:
    aliases = {compound.id: f"T_{_slug(compound.id).replace('-', '_')}" for compound in compounds}
    lines = [MERMAID_MARKER, "classDiagram"]
    for compound in sorted(compounds, key=lambda item: item.qualified_name):
        alias = aliases[compound.id]
        lines.append(f'    class {alias}["{compound.qualified_name}"]')
        if compound.kind == "interface":
            lines.append(f"    <<interface>> {alias}")
    arrows = {"implements": "..|>", "inherits": "--|>", "signature": "-->"}
    for source, target, relation in relations:
        lines.append(f"    {aliases[source.id]} {arrows[relation]} {aliases[target.id]} : {relation}")
    lines.append("")
    return "\n".join(lines)


def render_outputs(config: Config) -> dict[Path, str]:
    compounds = load_compounds(config)
    assign_components(config, compounds)
    resolver = LinkResolver(compounds)
    by_id = {compound.id: compound for compound in compounds}
    outputs: dict[Path, str] = {}
    for component in config.components:
        owned = [compound for compound in compounds if compound.component == component]
        component_relations = [
            relation
            for relation in _relations(compounds)
            if relation[0].component == component and relation[1].component == component
        ]
        outputs[component.output_dir / "code.md"] = _render_guide(
            config, component, owned, resolver, component_relations
        )
        outputs[component.output_dir / "_code-diagrams" / "types.mmd"] = _render_diagram(
            owned, component_relations
        )
        for compound in owned:
            path = _api_path(compound)
            if any(str(existing).casefold() == str(path).casefold() for existing in outputs):
                raise DocumentationError(f"colliding generated API path: {path}")
            outputs[path] = _render_api(config, compound, resolver, by_id)
    clean_outputs = {}
    for path, content in outputs.items():
        lines = []
        fenced = False
        for line in content.replace("\r\n", "\n").splitlines():
            if line.startswith("```"):
                fenced = not fenced
            line = line.rstrip()
            if not fenced and not line and lines and not lines[-1]:
                continue
            lines.append(line)
        clean_outputs[path] = "\n".join(lines).rstrip() + "\n"
    return clean_outputs


def _generated_files(config: Config) -> set[Path]:
    result: set[Path] = set()
    for component in config.components:
        candidates = [component.output_dir / "code.md"]
        if component.output_dir.exists():
            candidates.extend((component.output_dir / "api").rglob("*.md") if (component.output_dir / "api").exists() else [])
            candidates.extend(
                (component.output_dir / "_code-diagrams").rglob("*.mmd")
                if (component.output_dir / "_code-diagrams").exists()
                else []
            )
        for path in candidates:
            if path.is_file():
                first = path.read_text(encoding="utf-8").splitlines()[0:1]
                if first and first[0] in {GENERATED_MARKER, MERMAID_MARKER}:
                    result.add(path.resolve())
    return result


def _broken_links(outputs: dict[Path, str]) -> list[str]:
    expected = {path.resolve() for path in outputs}
    broken: list[str] = []
    pattern = re.compile(r"\[[^\]]+\]\(([^)]+)\)")
    for page, content in outputs.items():
        if page.suffix != ".md":
            continue
        for raw in pattern.findall(content):
            if re.match(r"^[a-z][a-z0-9+.-]*:", raw, flags=re.IGNORECASE) or raw.startswith("#"):
                continue
            target_text = raw.split("#", 1)[0]
            target = (page.parent / target_text).resolve()
            if target not in expected and not target.exists():
                broken.append(f"{page}: {raw}")
    return broken


def synchronize(config: Config, check: bool) -> list[str]:
    outputs = render_outputs(config)
    for path in outputs:
        if path.is_file():
            first = path.read_text(encoding="utf-8").splitlines()[0:1]
            if not first or first[0] not in {GENERATED_MARKER, MERMAID_MARKER}:
                raise DocumentationError(f"refusing to replace a file not owned by this generator: {path}")
    broken = _broken_links(outputs)
    if broken:
        raise DocumentationError("broken generated links:\n" + "\n".join(broken))
    expected = {path.resolve() for path in outputs}
    existing_generated = _generated_files(config)
    orphans = sorted(existing_generated - expected)
    stale = sorted(
        path
        for path, content in outputs.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    )
    messages: list[str] = []
    if check:
        messages.extend(f"stale generated output: {path}" for path in stale)
        messages.extend(f"orphan generated output: {path}" for path in orphans)
        return messages

    for path in orphans:
        path.unlink()
        messages.append(f"removed orphan: {path}")
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            messages.append(f"wrote: {path}")
    return messages
